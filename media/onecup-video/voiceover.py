"""Builds the voice-over track from voiceover.json with Kokoro TTS (offline, ONNX).

    python3 voiceover.py <kokoro-v1.0.onnx> <voices-v1.0.bin> <out.wav> [<subtitles.srt>]

Each line is read slowly (speed 0.86, at most 0.95 if it would not fit) with a pause between its
sentences, starts 0.18 s after its scene lands and must end 0.22 s before the next scene slides in.
The start time of every sentence goes to vo-timing.js, which timeline.js reads so the pictures
appear as the words are said. Timing constants match timeline.js.
"""
import json
import re
import sys
from pathlib import Path

import numpy as np
import soundfile as sf
from kokoro_onnx import Kokoro
from scipy.signal import resample_poly

model_p, voices_p, out_p = sys.argv[1:4]
srt_p = sys.argv[4] if len(sys.argv) > 4 else None

BEAT = 60 / 118.0
BAR = 4 * BEAT
BREAK = 432 / 24
END = 2054 / 24
SR = 48000
here = Path(__file__).parent


def at(b):
    if b == 'break':
        return BREAK
    if b == 'end':
        return END
    return 34.389 + (b - 17) * BAR


def sentences(text):
    return [s for s in re.split(r'(?<=[.?!])\s+', text.strip()) if s]


cfg = json.loads((here / 'voiceover.json').read_text())
k = Kokoro(model_p, voices_p)
track = np.zeros((int(END * SR) + SR, 2), dtype=np.float32)
report, subs, timing = [], [], {}
ok = True


def speak(text, speed):
    audio, sr = k.create(text, voice=cfg['voice'], speed=speed, lang='en-us')
    idx = np.where(np.abs(audio) > 0.01)[0]
    audio = audio[max(idx[0] - int(0.02 * sr), 0): idx[-1] + int(0.06 * sr)]
    return resample_poly(audio, SR, sr).astype(np.float32)


for line in cfg['lines']:
    start = max(at(line['bar']), 0.1) + 0.18
    stop = at(line['next']) - (0.6 if line['next'] == 'end' else 0.22)
    window = stop - start
    parts = sentences(line['text'])
    gaps = line.get('gaps', [cfg['gap']] * (len(parts) - 1))
    speed = cfg['speed']
    while True:
        clips = [speak(p, speed) for p in parts]
        dur = sum(len(c) for c in clips) / SR + sum(gaps)
        if dur <= window or speed >= cfg['max_speed']:
            break
        speed = min(cfg['max_speed'], round(speed * dur / window + 0.01, 3))
    fits = dur <= window
    ok &= fits
    peak = max(np.abs(c).max() for c in clips)
    t, starts = start, []
    for i, c in enumerate(clips):
        c = c * (0.8 / max(peak, 1e-6))
        s0 = int(t * SR)
        track[s0:s0 + len(c), 0] += c
        track[s0:s0 + len(c), 1] += c
        starts.append(round(t, 3))
        subs.append((t, t + len(c) / SR, parts[i]))
        t += len(c) / SR + (gaps[i] if i < len(gaps) else 0)
    timing[line['scene']] = {'s': starts, 'e': round(start + dur, 3)}
    report.append(f"{line['scene']}  {start:6.2f}–{start + dur:6.2f}s  window {window:4.2f}s  speed {speed:.2f}  "
                  f"{len(line['text'].split())} words  {'ok' if fits else 'TOO LONG'}")

sf.write(out_p, track[: int(END * SR)], SR, subtype='FLOAT')
(here / 'vo-timing.js').write_text(
    '// Generated by voiceover.py — start time (s) of every voice-over sentence, per scene.\n'
    f'window.VO = {json.dumps(timing, indent=1)};\n')
print('\n'.join(report))
if srt_p:
    def ts(x):
        h, r = divmod(x, 3600)
        m, s = divmod(r, 60)
        return f"{int(h):02d}:{int(m):02d}:{int(s):02d},{int(round((s % 1) * 1000)):03d}"
    Path(srt_p).write_text(''.join(f"{n}\n{ts(a)} --> {ts(b)}\n{x}\n\n" for n, (a, b, x) in enumerate(subs, 1)))
print('all lines fit' if ok else 'SOME LINES ARE TOO LONG')
